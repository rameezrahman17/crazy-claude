import type { ProjectProfile } from '../types.js';
import { has, runScript } from '../core/analyzer.js';

const CATEGORY_LABEL: Record<string, string> = {
  language: 'Languages', frontend: 'Frontend', backend: 'Backend', database: 'Database', orm: 'ORM / data access',
  testing: 'Testing', styling: 'Styling', infra: 'Infrastructure', auth: 'Auth', tooling: 'Tooling', graphics: 'Graphics',
};

const DIR_HINTS: Record<string, string> = {
  src: 'application source', app: 'routes / application entry', 'src/app': 'App Router routes', pages: 'page routes',
  'src/pages': 'page routes', components: 'shared UI components', 'src/components': 'shared UI components', lib: 'shared utilities',
  'src/lib': 'shared utilities', server: 'server-only code', 'src/server': 'server-only code', api: 'API handlers',
  routes: 'HTTP routes', controllers: 'request handlers', services: 'business logic', models: 'data models',
  prisma: 'Prisma schema & migrations', db: 'database code', migrations: 'database migrations', tests: 'tests', test: 'tests',
  __tests__: 'tests', e2e: 'end-to-end tests', public: 'static assets', packages: 'workspace packages', apps: 'workspace apps',
  scripts: 'tooling scripts', docs: 'documentation', supabase: 'Supabase config, migrations, functions',
};

const SCRIPT_ORDER = ['dev', 'start', 'build', 'test', 'test:e2e', 'e2e', 'lint', 'typecheck', 'type-check', 'format', 'db:migrate', 'db:push', 'db:generate'];

export const CLAUDE_MD_MARKER = '<!-- generated by crazy-claude -->';

export function generateClaudeMd(p: ProjectProfile): string {
  const out: string[] = [];
  const push = (...l: string[]) => out.push(...l);

  push(`# ${p.name}`, '', CLAUDE_MD_MARKER, '');
  if (p.description) push(p.description, '');

  // Tech stack
  push('## Tech stack', '');
  const byCat = new Map<string, string[]>();
  for (const t of p.technologies) {
    if (t.id === 'javascript' && has(p, 'typescript')) continue;
    byCat.set(t.category, [...(byCat.get(t.category) ?? []), t.name]);
  }
  for (const [cat, names] of byCat) push(`- **${CATEGORY_LABEL[cat] ?? cat}:** ${names.join(', ')}`);
  push(`- **Package manager:** ${p.packageManager}${p.isMonorepo ? ' (monorepo / workspaces)' : ''}`, '');

  // Commands
  const scripts = Object.keys(p.scripts);
  const ordered = [...SCRIPT_ORDER.filter((s) => scripts.includes(s)), ...scripts.filter((s) => !SCRIPT_ORDER.includes(s))].slice(0, 14);
  push('## Commands', '');
  if (ordered.length) {
    push('```bash');
    for (const s of ordered) push(`${runScript(p, s).padEnd(28)} # ${p.scripts[s]}`);
    push('```');
  } else if (has(p, 'python')) {
    push('```bash');
    if (has(p, 'django')) push('python manage.py runserver      # dev server', 'python manage.py migrate        # apply migrations');
    if (has(p, 'fastapi')) push('uvicorn main:app --reload        # dev server (adjust module path)');
    if (has(p, 'pytest')) push('pytest                           # run tests');
    if (has(p, 'ruff')) push('ruff check . && ruff format .    # lint + format');
    push('```');
  } else {
    push('_No scripts detected. Add the commands used to build, test and run this project._');
  }
  push('');

  // Structure
  if (p.directories.length) {
    push('## Project structure', '');
    for (const d of p.directories) push(`- \`${d}/\`${DIR_HINTS[d] ? ` — ${DIR_HINTS[d]}` : ''}`);
    push('');
  }

  // Conventions
  push('## Coding conventions', '');
  if (has(p, 'typescript')) push('- TypeScript is used: keep code strictly typed; avoid `any` and non-null assertions; prefer narrowing.');
  if (has(p, 'eslint')) push(`- ESLint is configured — run ${p.scripts.lint ? `\`${runScript(p, 'lint')}\`` : 'the linter'} before finishing a change.`);
  if (has(p, 'prettier')) push('- Formatting is owned by Prettier; do not hand-format or argue with it.');
  if (has(p, 'biome')) push('- Biome handles lint + format.');
  if (has(p, 'ruff')) push('- Python is linted and formatted with Ruff.');
  if (has(p, 'tailwind')) push('- Style with Tailwind utility classes; avoid new global CSS unless necessary.');
  push('- Match the patterns of neighboring files before introducing new ones.', '- Keep changes focused; do not refactor unrelated code in the same change.', '');

  // Architecture
  const arch: string[] = [];
  if (has(p, 'nextjs')) arch.push('- Next.js: default to Server Components; add `\'use client\'` only at interactive leaves. Server-only code must never be imported into client components.');
  else if (has(p, 'react')) arch.push('- React: keep components small and presentational; put data fetching and stateful logic in hooks.');
  if (has(p, 'vue')) arch.push('- Vue: use the Composition API with `<script setup>` for new components.');
  if (has(p, 'angular')) arch.push('- Angular: prefer standalone components and typed reactive forms.');
  if (has(p, 'nestjs')) arch.push('- NestJS: controllers stay thin; logic lives in providers/services; validate DTOs with pipes.');
  else if (has(p, 'express', 'fastify', 'hono')) arch.push('- HTTP layer: route handlers validate input and delegate to service functions; centralize error handling in middleware.');
  if (has(p, 'django')) arch.push('- Django: keep business logic out of views (use services/model methods); every model change needs a migration.');
  if (has(p, 'fastapi')) arch.push('- FastAPI: Pydantic models for request/response; dependencies (`Depends`) for auth and DB sessions.');
  if (p.isMonorepo) arch.push('- Monorepo: respect package boundaries; import across packages via their public entry points.');
  if (arch.length) push('## Architecture', '', ...arch, '');

  // Testing
  const testing = p.technologies.filter((t) => t.category === 'testing');
  push('## Testing', '');
  if (testing.length) {
    push(`- Frameworks: ${testing.map((t) => t.name).join(', ')}.`);
    if (p.scripts.test) push(`- Run: \`${runScript(p, 'test')}\``);
    push('- Add or update tests with every behavior change; reproduce bugs with a failing test first.', '- Never skip or delete failing tests to get a green run.');
  } else {
    push('- No test framework detected. Ask before introducing one, and propose the lightest fit for this stack.');
  }
  push('');

  // Database
  const data = p.technologies.filter((t) => t.category === 'database' || t.category === 'orm');
  if (data.length) {
    push('## Database', '', `- Stack: ${data.map((t) => t.name).join(', ')}.`);
    if (has(p, 'prisma')) push('- Schema lives in `schema.prisma`; change it, then create a migration with `prisma migrate dev --name <change>`.');
    if (has(p, 'drizzle')) push('- Schema is defined in TypeScript; generate migrations with `drizzle-kit generate`.');
    if (has(p, 'supabase')) push('- Supabase: keep Row Level Security enabled on every table; migrations live in `supabase/migrations`.');
    push('- Never run destructive operations (drop, truncate, reset) against shared databases.', '- Parameterize all queries; never build SQL from user input.', '');
  }

  // Security
  push('## Security', '', '- Never commit secrets. Read configuration from environment variables; keep `.env*` files out of git (`.env.example` documents the keys).', '- Do not edit `.env` files or private keys — ask the user.');
  if (has(p, 'nextjs')) push('- Only `NEXT_PUBLIC_*` variables reach the browser — never put secrets behind that prefix.');
  if (p.technologies.some((t) => t.category === 'auth')) push('- Every protected route/action must check authorization for the specific resource, not only authentication.');
  push('');

  push('## Working agreements', '', '- Before declaring a task done, run the relevant build/test/lint commands and report their real output.', '- When requirements are ambiguous, ask rather than guess.', '');
  return out.join('\n');
}
