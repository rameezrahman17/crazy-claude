import type { ProjectProfile } from '../types.js';
import { has, runScript } from '../core/analyzer.js';
import type { RegistryEntry } from './types.js';

/** Claude Code hook events used here — see https://code.claude.com/docs/en/hooks */
export type HookEvent = 'PreToolUse' | 'PostToolUse';

export interface HookRegistryEntry extends RegistryEntry {
  scriptName: string;
  event: HookEvent;
  matcher: string;
  timeout: number;
  script: (p: ProjectProfile) => string;
}

const hook = (e: Omit<HookRegistryEntry, 'type' | 'source' | 'requiresApproval' | 'compatibility' | 'id'>): HookRegistryEntry => ({
  ...e,
  id: `hook-${e.scriptName}`,
  type: 'hook',
  source: { trust: 'generated-local', origin: 'Generated by crazy-claude into .claude/hooks/crazy-claude/' },
  requiresApproval: false,
  compatibility: 'Claude Code hooks (settings.json). Requires Node.js on PATH.',
});

/** Shared prelude: read hook JSON from stdin. */
const READ_INPUT = `let raw = '';
for await (const chunk of process.stdin) raw += chunk;
let input = {};
try { input = JSON.parse(raw || '{}'); } catch { process.exit(0); }
const ti = input.tool_input ?? {};`;

